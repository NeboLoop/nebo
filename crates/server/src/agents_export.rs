//! `AGENTS.md`, rendered outward — the company's standing rules as one plain
//! file an outside coding tool reads before it works in a repository.
//!
//! `AGENTS.md` is a cross-vendor convention: a markdown file at a project's
//! root that tells whoever arrives how to work there. Its whole value is that
//! a tool which has never heard of this company can read one file and behave.
//! A company's rules live in Nebo's layers, which an outside tool knows
//! nothing about, so this module projects them into that file.
//!
//! The file is a **projection**. The layers stay the source of truth, editing
//! the rendered file changes nothing, and the next render overwrites it. The
//! file says so, in its own text, where someone about to edit it will read it.
//!
//! Two rules shape everything here.
//!
//! **One trigger.** The render happens in the one routine that makes every
//! seat re-read its layers, [`crate::layers_update::apply_pending`], and
//! nowhere else. There is no schedule and no second trigger.
//!
//! **One way out.** [`place`] is the only function that writes the render
//! anywhere, so "never clobber a project's own `AGENTS.md`" is a property of
//! the code rather than of a habit.
//!
//! And one thing this module refuses to do: the export leaves the machine, so
//! [`withhold_reason`] is a deliberate filter over every entry it would carry.
//! It is not the omission that happens to fall out of the code today.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use napp::pack::{PackEntry, PackLayer};
use tracing::{debug, info, warn};

/// The file name the standard established, at the project root.
pub const ROOT_FILE: &str = "AGENTS.md";

/// Where the render goes when the project already wrote its own `AGENTS.md`
/// and did not offer the markers.
pub const SIBLING_FILE: &str = "COMPANY-AGENTS.md";

/// The markers a project's own `AGENTS.md` may carry to take the render
/// inline. Everything outside them is the project's and is never touched.
pub const MERGE_START: &str = "<!-- company-rules: rendered, do not edit -->";
pub const MERGE_END: &str = "<!-- company-rules: end -->";

/// The line every render carries under its title, where someone about to edit
/// the file will read it. It is also how [`place`] tells its own earlier
/// render from a project's own `AGENTS.md`: a root file that carries this
/// line and no markers is ours to overwrite, and one that does not is theirs
/// to leave alone.
pub const RENDERED_NOTE: &str = "_Rendered from this company's standing rules. Do not edit this file: \
it is written from somewhere else, an edit here changes nothing, and the next render overwrites it. \
To change what it says, change the company's own rules and let the render follow._";

/// The standard `company.` id that says how long an ask stays good. The
/// one-way constraint needs it; nothing else of the reserved namespace is
/// read here, because the rest of it is money and money does not leave.
const ASK_EXPIRY_ID: &str = "company.unattended.grant_freshness_secs";

/// Everything the render reads, gathered once. Plain data on purpose: the
/// render is a pure function of it, which is what makes it testable and what
/// makes re-rendering the same layers produce the same bytes.
#[derive(Debug, Default)]
pub struct Company<'a> {
    /// The company's own display name, from the company layer.
    pub name: &'a str,
    /// The applied layer snapshot — the resolved stack, not one pack.
    pub packs: Vec<&'a napp::Pack>,
    /// The capabilities the company has actually connected. A rule about
    /// something this company cannot reach is not a build instruction.
    pub connected: BTreeSet<String>,
    /// Operation suffixes the company reserves to the owner's own hand.
    pub reserved: BTreeSet<String>,
    /// Operation suffixes a seat holds at approval — its own ceiling.
    pub ceilings: BTreeSet<String>,
    /// How long an ask stays good, in seconds. `None` = the company has not
    /// said, and the render states the safe default instead of a number.
    pub ask_expiry_secs: Option<i64>,
    /// The moment the layers were read, as a unix timestamp.
    pub resolved_at: i64,
}

/// Which file the render landed in, and whether the project's own file was
/// left alone. Every branch says the project's file is intact, because every
/// branch leaves it intact.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Placed {
    /// The project had no `AGENTS.md`; the render is it.
    Root,
    /// The project's own `AGENTS.md` offered the markers; the render sits
    /// between them and nothing outside them moved.
    Merged,
    /// The project's own `AGENTS.md` stands untouched; the render is beside
    /// it under [`SIBLING_FILE`].
    Sibling,
    /// The bytes on disk already said this. Nothing was written.
    Unchanged,
}

