    /// The same layers render the same bytes, and placing them twice writes
    /// once. A render that churned would show up as a diff in every
    /// repository every time anything else changed.
    #[test]
    fn re_rendering_is_idempotent() {
        let tmp = tempfile::tempdir().unwrap();
        let pack = company_pack(tmp.path());
        let first = render(&sample(&[&pack]));
        let second = render(&sample(&[&pack]));
        assert_eq!(first, second, "the same layers must render the same bytes");

        let root = tmp.path().join("project");
        std::fs::create_dir_all(root.join(".git")).unwrap();
        assert_eq!(place(&root, &first).unwrap(), Placed::Root);
        assert_eq!(place(&root, &second).unwrap(), Placed::Unchanged);
        assert_eq!(std::fs::read_to_string(root.join(ROOT_FILE)).unwrap(), first);
        assert!(!root.join(SIBLING_FILE).exists(), "our own render is not mistaken for the project's");

        // A later render of the same company replaces our earlier one in
        // place, rather than piling a sibling beside it.
        let packs = [&pack];
        let mut later = sample(&packs);
        later.resolved_at += 60;
        let third = render(&later);
        assert_ne!(third, first);
        assert_eq!(place(&root, &third).unwrap(), Placed::Root);
        assert_eq!(std::fs::read_to_string(root.join(ROOT_FILE)).unwrap(), third);
        assert!(!root.join(SIBLING_FILE).exists());

        // Through the markers, twice, is also once: the block is replaced,
        // never appended.
        let merged = tmp.path().join("merged");
        std::fs::create_dir_all(merged.join(".git")).unwrap();
        std::fs::write(
            merged.join(ROOT_FILE),
            format!("# Our project\n\nRun `make test`.\n\n{MERGE_START}\nold\n{MERGE_END}\n\nThat is all.\n"),
        )
        .unwrap();
        assert_eq!(place(&merged, &first).unwrap(), Placed::Merged);
        let once = std::fs::read_to_string(merged.join(ROOT_FILE)).unwrap();
        assert_eq!(place(&merged, &first).unwrap(), Placed::Unchanged);
        assert_eq!(std::fs::read_to_string(merged.join(ROOT_FILE)).unwrap(), once);
        assert_eq!(once.matches(MERGE_START).count(), 1, "{once}");
    }

    /// A project's own `AGENTS.md` is the project's. Clobbering it is how a
    /// company loses the build instructions that were the reason the file
    /// existed, which is the normal case, so it is checked rather than
    /// trusted.
    #[test]
    fn a_projects_own_agents_file_is_never_destroyed() {
        let tmp = tempfile::tempdir().unwrap();
        let pack = company_pack(tmp.path());
        let rendered = render(&sample(&[&pack]));

        // No markers: the project's file is not touched at all and the render
        // sits beside it.
        let root = tmp.path().join("theirs");
        std::fs::create_dir_all(root.join(".git")).unwrap();
        let theirs = "# Their project\n\nBuild with `make`. Do not hand-edit `gen/`.\n";
        std::fs::write(root.join(ROOT_FILE), theirs).unwrap();
        assert_eq!(place(&root, &rendered).unwrap(), Placed::Sibling);
        assert_eq!(std::fs::read_to_string(root.join(ROOT_FILE)).unwrap(), theirs);
        assert_eq!(std::fs::read_to_string(root.join(SIBLING_FILE)).unwrap(), rendered);

        // Markers: everything outside them survives, to the byte.
        let merged = tmp.path().join("ours");
        std::fs::create_dir_all(merged.join(".git")).unwrap();
        std::fs::write(
            merged.join(ROOT_FILE),
            format!("# Ours\n\nBuild with `make`.\n\n{MERGE_START}\nstale\n{MERGE_END}\n\nReviewers block on tests.\n"),
        )
        .unwrap();
        place(&merged, &rendered).unwrap();
        let after = std::fs::read_to_string(merged.join(ROOT_FILE)).unwrap();
        assert!(after.starts_with("# Ours\n\nBuild with `make`."), "{after}");
        assert!(after.trim_end().ends_with("Reviewers block on tests."), "{after}");
        assert!(after.contains("rules for work in this repository"), "{after}");
        assert!(!after.contains("stale"), "{after}");
        assert!(!merged.join(SIBLING_FILE).exists(), "the sibling is not also written");

        // And a directory that is not a repository gets nothing.
        let plain = tmp.path().join("notes");
        std::fs::create_dir_all(&plain).unwrap();
        assert!(place_known(&plain).is_none());
        assert!(!plain.join(ROOT_FILE).exists());
    }

