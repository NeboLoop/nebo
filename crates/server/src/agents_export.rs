/// What kind of thing a resolved entry is. The kind gate is deterministic and
/// lives here: `vocabulary/`, `parties/`, `workflows/` and `reference/` are
/// never carried at all — they describe the trade, the people in it, the
/// company's own procedures, and material far too large for a file meant to
/// be read in full.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Kind {
    Law,
    Rule,
    Standard,
}

struct Resolved<'a> {
    kind: Kind,
    entry: &'a PackEntry,
    /// A law's operation suffixes.
    ceiling: Vec<String>,
    /// A law the company reserves to the owner's own hand rather than blocking.
    owner_reserved: bool,
    /// A rule pinned with `always: true`.
    always: bool,
}

/// The stack collapsed: higher layer wins, a silent layer falls through. Keyed
/// by kind and file name, which is how a company rule replaces the industry
/// rule it was written to replace.
fn resolve<'a>(packs: &[&'a napp::Pack]) -> Vec<Resolved<'a>> {
    let mut ordered: Vec<&&napp::Pack> = packs.iter().collect();
    ordered.sort_by_key(|p| p.layer.rank());
    let mut out: BTreeMap<(Kind, String), Resolved<'a>> = BTreeMap::new();
    for pack in ordered {
        for law in &pack.laws {
            out.insert(
                (Kind::Law, law.entry.name.clone()),
                Resolved {
                    kind: Kind::Law,
                    entry: &law.entry,
                    ceiling: law.ceiling.clone(),
                    // `reserved_to: owner` holds on the company layer only —
                    // the same rule the runtime applies when it reads the
                    // reserved list from the company pack alone.
                    owner_reserved: pack.layer == PackLayer::Company && law.is_owner_reserved(),
                    always: false,
                },
            );
        }
        for rule in &pack.rules {
            out.insert(
                (Kind::Rule, rule.entry.name.clone()),
                Resolved {
                    kind: Kind::Rule,
                    entry: &rule.entry,
                    ceiling: Vec::new(),
                    owner_reserved: false,
                    always: rule.always,
                },
            );
        }
        // An industry standard is a number for the trade, not a statement
        // about how software is built here; the kind gate stops it.
        if pack.layer != PackLayer::Industry {
            for s in &pack.standards {
                out.insert(
                    (Kind::Standard, s.entry.name.clone()),
                    Resolved {
                        kind: Kind::Standard,
                        entry: &s.entry,
                        ceiling: Vec::new(),
                        owner_reserved: false,
                        always: false,
                    },
                );
            }
        }
    }
    out.into_values().collect()
}

fn surface(entry: &PackEntry) -> Option<&str> {
    entry.frontmatter.get("surface").and_then(|v| v.as_str())
}

/// The capability half of an operation suffix (`ledger.bill.create` → `ledger`).
fn capability_of(op: &str) -> &str {
    op.split('.').next().unwrap_or(op)
}

