/// The ONE way the render lands anywhere.
///
/// A project's own `AGENTS.md` is the project's. Clobbering it is how a
/// company loses the build instructions that were the reason the file existed,
/// so this function never writes over one:
///
/// * no `AGENTS.md` — the render is it, under the name the standard
///   established and in the place an outside tool already looks;
/// * an `AGENTS.md` carrying both markers — the render goes between them and
///   every byte outside them stays where it was;
/// * an `AGENTS.md` that is an earlier render of ours, whole — overwritten,
///   which is what the file says will happen to it;
/// * any other `AGENTS.md` — it is not touched at all, and the render sits
///   beside it as `COMPANY-AGENTS.md`. The render does not invent the markers
///   in somebody else's file.
///
/// Writing the same bytes twice is not a write, so a repository does not churn.
pub fn place(root: &Path, rendered: &str) -> std::io::Result<Placed> {
    let own = root.join(ROOT_FILE);
    let existing = std::fs::read_to_string(&own).ok();
    let (target, text, placed) = match &existing {
        None => (own.clone(), rendered.to_string(), Placed::Root),
        Some(text) if text.contains(MERGE_START) && text.contains(MERGE_END) => (
            own.clone(),
            tools::rules_tool::merge_marked_block(text, MERGE_START, MERGE_END, rendered),
            Placed::Merged,
        ),
        // An earlier render of ours, whole: the next render overwrites it, as
        // the file itself says it will.
        Some(text) if text.contains(RENDERED_NOTE) => (own.clone(), rendered.to_string(), Placed::Root),
        Some(_) => (root.join(SIBLING_FILE), rendered.to_string(), Placed::Sibling),
    };
    if std::fs::read_to_string(&target).is_ok_and(|on_disk| on_disk == text) {
        return Ok(Placed::Unchanged);
    }
    std::fs::write(&target, text)?;
    Ok(placed)
}

/// Where the render is kept for a repository Nebo was never told the path of.
/// A coding seat is pointed at a repository when the work happens, not when
/// the layers change, so the render is written here once and placed from here.
pub fn known_file() -> Option<std::path::PathBuf> {
    config::data_dir().ok().map(|d| d.join(ROOT_FILE))
}

/// Put the standing render into a project root. Returns `None` when there is
/// nothing to place — no layers applied yet, or the directory is not a project.
///
/// The gate is a git work tree: the owner points an employee at a folder to
/// work in, which is not by itself permission to leave a file in it, and a
/// repository is the one place `AGENTS.md` means anything.
pub fn place_known(root: &Path) -> Option<Placed> {
    if !root.join(".git").exists() {
        return None;
    }
    let rendered = std::fs::read_to_string(known_file()?).ok()?;
    match place(root, &rendered) {
        Ok(Placed::Unchanged) => None,
        Ok(placed) => {
            info!(root = %root.display(), ?placed, "company rules placed for an outside agent");
            Some(placed)
        }
        Err(e) => {
            warn!(root = %root.display(), error = %e, "company rules not placed");
            None
        }
    }
}

/// Re-render, from the applied layer snapshot. The ONE caller is
/// [`crate::layers_update::apply_pending`]: the same event that makes every
/// seat re-read its layers gives the export its re-render, and there is no
/// second trigger and no schedule.
pub fn rerender(state: &crate::state::AppState, applied: &std::collections::HashMap<String, napp::Pack>) {
    let Some(path) = known_file() else { return };
    let packs: Vec<&napp::Pack> = applied.values().collect();
    let Some(company) = packs.iter().find(|p| p.layer == PackLayer::Company) else {
        // No company layer is no company voice. A render left behind would go
        // on speaking for a company that no longer says it.
        let _ = std::fs::remove_file(&path);
        debug!("agents export: no company layer, nothing to render");
        return;
    };

    // The capabilities the company has actually connected: what an installed,
    // enabled, ready plugin binds. A rule about something this company cannot
    // reach is not a build instruction.
    let mut connected: BTreeSet<String> = BTreeSet::new();
    for slug in tools::plugin_tool::active_plugin_slugs(&state.plugin_store, &state.store) {
        if let Some(m) = state.plugin_store.get_manifest(&slug) {
            for op in m.interface_bindings.keys() {
                connected.insert(capability_of(op).to_string());
            }
        }
    }

    let reserved: BTreeSet<String> = tools::policy::CompanyPolicy::from_json(
        state.store.get_company_policy().ok().flatten().as_deref(),
    )
    .reserved
    .into_iter()
    .collect();

    // Every enabled seat's own ceiling. Which seats have standing work in a
    // given repository is not something Nebo records, so the union is used:
    // it is the stricter reading, and an outside agent that asks about one
    // operation too many has cost a sentence.
    let mut ceilings: BTreeSet<String> = BTreeSet::new();
    for seat in state
        .store
        .list_agents(10_000, 0)
        .unwrap_or_default()
        .iter()
        .filter(|a| a.is_enabled == 1 && a.is_app.unwrap_or(0) == 0)
    {
        for rule in state
            .store
            .permission_rules_in(&types::permissions::Scope::Employee(seat.id.clone()))
            .unwrap_or_default()
        {
            if let (types::permissions::RuleKey::Operation(op), types::permissions::Effect::Ask) = (&rule.key, rule.effect) {
                ceilings.insert(op.clone());
            }
        }
    }

    let ask_expiry_secs = packs
        .iter()
        .filter(|p| p.layer == PackLayer::Company)
        .find_map(|p| p.defaults().get(ASK_EXPIRY_ID).and_then(|v| v.as_i64()));

    let name = company.name.clone();
    let rendered = render(&Company {
        name: &name,
        packs: packs.clone(),
        connected,
        reserved,
        ceilings,
        ask_expiry_secs,
        resolved_at: chrono::Utc::now().timestamp(),
    });
    let root = path.parent().map(Path::to_path_buf).unwrap_or_default();
    match place(&root, &rendered) {
        Ok(placed) => info!(?placed, path = %path.display(), "company rules rendered for an outside agent"),
        Err(e) => warn!(error = %e, path = %path.display(), "company rules not rendered"),
    }
}

