/// Resources whose names run two words together in an operation address.
const NOUNS: &[(&str, &str)] = &[
    ("billpayment", "bill payment"),
    ("journalentry", "journal entry"),
    ("creditmemo", "credit memo"),
    ("po", "purchase order"),
    ("fulfillment", "fulfilment record"),
    ("opportunity", "sales opportunity"),
];

fn verb(action: &str) -> Option<&'static str> {
    Some(match action {
        "create" => "Creating",
        "upsert" => "Creating or changing",
        "update" => "Changing",
        "status" => "Changing the status of",
        "send" => "Sending",
        "reply" => "Replying to",
        "respond" => "Responding to",
        "schedule" => "Scheduling",
        "publish" => "Publishing",
        "apply" => "Applying",
        "record" => "Recording",
        "attach" => "Attaching",
        "write" => "Writing",
        "remove" | "delete" => "Deleting",
        _ => return None,
    })
}

/// One operation as a sentence an outside reader can act on, naming no
/// address, no capability and no semantic id — a reader who has to learn this
/// company's vocabulary to obey it has been handed the wrong file.
fn in_plain_words(suffix: &str) -> Option<String> {
    let parts: Vec<&str> = suffix.split('.').collect();
    let (resource, action) = match parts.as_slice() {
        [_, r, a] => (*r, *a),
        [r, a] => (*r, *a),
        _ => return None,
    };
    let noun = NOUNS
        .iter()
        .find(|(k, _)| *k == resource)
        .map(|(_, v)| (*v).to_string())
        .unwrap_or_else(|| resource.replace(['-', '_'], " "));
    let article = if noun.starts_with(['a', 'e', 'i', 'o', 'u']) { "an" } else { "a" };
    Some(format!("{} {article} {noun}", verb(action)?))
}

