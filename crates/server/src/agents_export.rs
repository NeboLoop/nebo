/// Domains that are fixtures by convention and are not anybody's.
const EXAMPLE_DOMAINS: &[&str] = &["example.com", "example.org", "example.net"];

/// Top-level domains worth recognising in a hostname. Short on purpose: a
/// long list starts matching file extensions.
const TLDS: &[&str] = &[
    "com", "net", "org", "io", "ai", "co", "dev", "app", "edu", "gov", "biz", "info", "us", "uk",
    "ca", "au", "de", "fr", "cloud", "email",
];

/// How a minted credential starts. Matched at the start of a WORD and only
/// when enough follows to be a real one: `sk-` as a bare substring is in
/// "task-based" and "risk-free", and a filter that withheld those would
/// withhold half of what is worth exporting.
const CREDENTIAL_PREFIXES: &[&str] = &[
    "sk-", "sk_live", "sk_test", "pk_live", "rk_live", "AKIA", "ASIA", "ghp_", "gho_",
    "github_pat_", "xoxb-", "xoxp-", "xapp-", "AIza", "ya29.", "eyJ", "glpat-", "npm_", "SG.",
    "shpat_",
];

/// A word that starts like a minted credential and is long enough to be one.
fn has_credential_prefix(text: &str) -> bool {
    text.split(|c: char| c.is_whitespace() || matches!(c, '"' | '\'' | '(' | ')' | ',' | ';' | '='))
        .any(|w| {
            let w = w.trim_start_matches(|c: char| !c.is_ascii_alphanumeric());
            CREDENTIAL_PREFIXES
                .iter()
                .any(|p| w.starts_with(p) && w.len() >= p.len() + 8)
        })
}

/// The word half of a `key: value` credential. Matched only when a value
/// follows, so a rule that SAYS "never commit a credential or a token" is
/// carried and a line that hands one over is not. Refusing the word instead
/// of the value would withhold exactly the rules worth exporting.
const SECRET_WORDS: &[&str] = &[
    "api key", "api_key", "apikey", "secret", "password", "passwd", "access token", "auth token",
    "authtoken", "bearer", "private key", "client_secret", "connection string", "dsn",
];

const URL_SCHEMES: &[&str] = &[
    "postgres://", "postgresql://", "mysql://", "mongodb://", "mongodb+srv://", "redis://",
    "amqp://", "amqps://", "ftp://",
];

fn is_secret_value(rest: &str) -> bool {
    let v = rest.trim_start_matches([' ', '=', ':', '"', '\'']);
    let token: &str = v.split_whitespace().next().unwrap_or("");
    let token = token.trim_matches(|c: char| matches!(c, '"' | '\'' | ',' | '.' | ')' | ';'));
    token.len() >= 8
        && token.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '+' | '/' | '='))
        && token.chars().any(|c| c.is_ascii_digit())
}

/// A run of at least 24 characters that looks minted rather than written:
/// mixed case, a digit, and no spaces. What a leaked key looks like when it
/// carries no recognisable prefix.
fn has_minted_token(text: &str) -> bool {
    text.split_whitespace().any(|w| {
        let w = w.trim_matches(|c: char| !c.is_ascii_alphanumeric());
        w.len() >= 24
            && w.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '+' | '/' | '='))
            && w.chars().any(|c| c.is_ascii_uppercase())
            && w.chars().any(|c| c.is_ascii_lowercase())
            && w.chars().any(|c| c.is_ascii_digit())
    })
}

fn has_email(text: &str) -> bool {
    text.split(|c: char| c.is_whitespace() || matches!(c, '<' | '>' | '(' | ')' | ',' | ';'))
        .any(|w| {
            let w = w.trim_end_matches(['.', ':', '"', '\'']);
            let Some((local, domain)) = w.split_once('@') else { return false };
            !local.is_empty()
                && !local.contains('@')
                && looks_like_host(domain)
                && !is_example_host(domain)
        })
}

/// `example.com` and its subdomains are fixtures by convention and are
/// nobody's, so they are the one host shape that may leave.
fn is_example_host(host: &str) -> bool {
    let host = host.to_ascii_lowercase();
    EXAMPLE_DOMAINS
        .iter()
        .any(|d| host == *d || host.ends_with(&format!(".{d}")))
}

fn looks_like_host(host: &str) -> bool {
    let host = host.trim_end_matches('.');
    let Some((label, tld)) = host.rsplit_once('.') else { return false };
    !label.is_empty()
        && label.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '.'))
        && TLDS.iter().any(|t| tld.eq_ignore_ascii_case(t))
}

/// A hostname or a domain anywhere in the text. `example.com` and friends are
/// fixtures; everything else is somebody's, and the export is published.
fn has_domain(text: &str) -> bool {
    text.split(|c: char| c.is_whitespace() || matches!(c, '<' | '>' | '(' | ')' | ',' | ';' | '"' | '\''))
        .any(|w| {
            let w = w.trim_start_matches(|c: char| !c.is_ascii_alphanumeric());
            let w = w.split('/').next().unwrap_or(w);
            let w = w.rsplit('@').next().unwrap_or(w);
            let w = w.split(':').next().unwrap_or(w);
            let w = w.trim_end_matches(['.', '!', '?']);
            looks_like_host(w) && !is_example_host(w)
        })
}

/// A telephone number. Tight shapes only: a loose "ten or more digits and
/// separators" rule reads a timestamp as a phone number.
fn has_phone(text: &str) -> bool {
    let b: Vec<char> = text.chars().collect();
    let digits_at = |i: usize, n: usize| {
        i + n <= b.len() && (0..n).all(|k| b[i + k].is_ascii_digit())
    };
    for i in 0..b.len() {
        // +1 555 867 5309 / +44 20 7946 0958
        if b[i] == '+' && digits_at(i + 1, 1) {
            let run: String = b[i + 1..]
                .iter()
                .take_while(|c| c.is_ascii_digit() || matches!(c, ' ' | '-' | '.' | '(' | ')'))
                .collect();
            if run.chars().filter(|c| c.is_ascii_digit()).count() >= 9 {
                return true;
            }
        }
        // (555) 867-5309
        if b[i] == '(' && digits_at(i + 1, 3) && b.get(i + 4) == Some(&')') {
            return true;
        }
        // 555-867-5309 and 555.867.5309
        if digits_at(i, 3)
            && matches!(b.get(i + 3), Some('-') | Some('.'))
            && digits_at(i + 4, 3)
            && matches!(b.get(i + 7), Some('-') | Some('.'))
            && digits_at(i + 8, 4)
        {
            return true;
        }
        // A bare ten- or eleven-digit run, not part of a longer number.
        if digits_at(i, 10)
            && (i == 0 || !b[i - 1].is_ascii_digit())
            && !digits_at(i, 12)
        {
            return true;
        }
    }
    false
}

/// A money figure. The export carries no amount the company has not already
/// published, and nothing in the layers marks an amount as published, so an
/// amount withholds the entry that carries it. Money is not a build
/// instruction; the withheld list tells the owner it was left out.
fn has_money(text: &str) -> bool {
    let lower = text.to_ascii_lowercase();
    let b: Vec<char> = lower.chars().collect();
    for i in 0..b.len() {
        if matches!(b[i], '$' | '€' | '£' | '¥')
            && b[i + 1..].iter().take(2).any(|c| c.is_ascii_digit())
        {
            return true;
        }
        if b[i].is_ascii_digit() && (i == 0 || !b[i - 1].is_ascii_digit()) {
            let tail: String = b[i..].iter().take(24).collect();
            let after = tail.trim_start_matches(|c: char| c.is_ascii_digit() || matches!(c, ',' | '.' | '_'));
            for unit in ["usd", "eur", "gbp", "dollar", "cent", "euro"] {
                if after.trim_start().starts_with(unit) {
                    return true;
                }
            }
        }
    }
    lower.contains("_cents")
}

/// Why this text may not leave the machine, in the owner's words rather than
/// a pattern name. `None` = it may.
///
/// This is the filter, and it is deliberate. Five things never leave, and the
/// entry carrying one of them is withheld whole — a `surface: code` on the
/// entry does not buy its way past this, because "without exception" is what
/// the specification says and a published file is a published file.
pub fn withhold_reason(text: &str) -> Option<&'static str> {
    if text.contains(tools::rules_tool::PACKAGES_START)
        || text.contains(tools::rules_tool::PACKAGES_END)
    {
        return Some("it carries an employee's own written context");
    }
    let lower = text.to_ascii_lowercase();
    if text.contains("-----BEGIN")
        || has_credential_prefix(text)
        || URL_SCHEMES.iter().any(|s| lower.contains(s))
        || has_minted_token(text)
    {
        return Some("it carries something that looks like a credential");
    }
    for word in SECRET_WORDS {
        let mut from = 0usize;
        while let Some(at) = lower[from..].find(word) {
            let end = from + at + word.len();
            if is_secret_value(&lower[end..]) {
                return Some("it carries something that looks like a credential");
            }
            from = end;
        }
    }
    if has_email(text) || has_phone(text) || has_domain(text) {
        return Some("it names somebody outside this company");
    }
    if has_money(text) {
        return Some("it states a money figure");
    }
    None
}

